  keys = {
    {
      "<leader>e",
      function()
        local explorer_win = nil

        -- Buscar si ya hay un explorer abierto (Snacks usa este filetype)
        for _, win in ipairs(vim.api.nvim_list_wins()) do
          local buf = vim.api.nvim_win_get_buf(win)
          local ft = vim.bo[buf].filetype
          if ft == "snacks_picker_list" then
            explorer_win = win
            break
          end
        end

        if explorer_win and vim.api.nvim_get_current_win() ~= explorer_win then
          -- Si ya existe y no estamos en él → hacer focus
          vim.api.nvim_set_current_win(explorer_win)
        else
          -- Si no existe (o estamos en él) → toggle normal
          Snacks.explorer()
        end
      end,
      desc = "Snacks File Explorer (focus / toggle)",
    },
  },
